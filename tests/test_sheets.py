@needs_openssl
def test_missing_data_tabs_are_created_and_report_tabs_are_left_alone(key_file):
    google = FakeGoogle(key_file, tabs=("days", "my report", "charts"))

    _, sheet = check(key_file, "sheet-1", google)

    assert sheet.created_tabs == ("trades", "argus_fills", "broker_txns", "recon")
    assert all("addSheet" in w for w in google.writes)
    assert {"my report", "charts"} <= set(google.tabs), "nothing of the operator's touched"
    assert set(DATA_TABS) <= set(google.tabs)


@needs_openssl
def test_with_every_tab_present_a_harmless_write_still_proves_editor_access(key_file):
    """Otherwise `check` would pass on a read-only share and fail on the first push."""
    google = FakeGoogle(key_file, tabs=DATA_TABS)

    _, sheet = check(key_file, "sheet-1", google)

    assert sheet.created_tabs == ()
    assert google.writes == [{"updateSpreadsheetProperties": {
        "properties": {"title": "Argus ledger"}, "fields": "title",
    }}], "a title set to what it already is: a write that changes nothing"


# -- refusals -----------------------------------------------------------------


def test_an_oauth_client_file_is_named_as_the_wrong_file(tmp_path):
    path = tmp_path / "client_secret.json"
    path.write_text(json.dumps({"installed": {"client_id": "x", "client_secret": "y"}}))

    with pytest.raises(SheetsError, match="OAuth client file, not a service-account"):
        load_key(path)


def test_a_key_file_that_is_not_json_or_has_no_email_is_refused(tmp_path):
    bad = tmp_path / "bad.json"
    bad.write_text("{oops")
    with pytest.raises(SheetsError, match="cannot read the key file"):
        load_key(bad)

    no_email = tmp_path / "no-email.json"
    no_email.write_text(json.dumps({"private_key": "x", "type": "service_account"}))
    with pytest.raises(SheetsError, match="unreadable private_key"):
        load_key(no_email)


@needs_openssl
def test_a_token_endpoint_that_returns_no_token_is_refused(key_file):
    with pytest.raises(SheetsError, match="no access_token"):
        check(key_file, "sheet-1", lambda req: {})


def test_googles_own_error_text_is_what_surfaces():
    assert sheets._google_error(
        b'{"error": {"message": "The caller does not have permission"}}'
    ) == "The caller does not have permission"
    assert sheets._google_error(
        b'{"error": "invalid_grant", "error_description": "Invalid JWT Signature."}'
    ) == "Invalid JWT Signature."
    assert sheets._google_error(b"<html>502</html>").startswith("<html>")


