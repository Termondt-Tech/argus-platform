"""The Google Sheets credential and calls (`argus.tools.sheets`).

Nothing here reaches Google. The transport is a fake that answers like Google does
and, at the token endpoint, **verifies the assertion the way Google would** — the
signature against the key's public exponent, and the claims — so a malformed JWT
fails these tests rather than only failing in production.

The key is generated by `openssl` at test time and shaped like the JSON Google
downloads. No key is committed.
"""

from __future__ import annotations

import ast
import csv
import json
import shutil
import subprocess
import time
import urllib.parse
import urllib.request
from pathlib import Path

import pytest

from argus.tools import sheets
from argus.tools.rs256 import load_pem_private_key, verify
from argus.tools.sheets import (
    DATA_TABS,
    SCOPE,
    SheetsError,
    build_assertion,
    check,
    load_key,
)

openssl = shutil.which("openssl")
needs_openssl = pytest.mark.skipif(openssl is None, reason="openssl not on PATH")

EMAIL = "ledger@example.iam.gserviceaccount.com"


@pytest.fixture
def key_file(tmp_path: Path) -> Path:
    """A service-account key file shaped exactly like Google's download."""
    pem = tmp_path / "key.pem"
    subprocess.run(
        [openssl, "genpkey", "-algorithm", "RSA", "-out", str(pem),
         "-pkeyopt", "rsa_keygen_bits:2048"],
        check=True, capture_output=True,
    )
    path = tmp_path / "argus-sheets-key.json"
    path.write_text(json.dumps({
        "type": "service_account",
        "project_id": "argus-ledger-1",
        "private_key_id": "abc123",
        "private_key": pem.read_text(),
        "client_email": EMAIL,
        "client_id": "1234567890",
        "token_uri": "https://oauth2.googleapis.com/token",
    }))
    return path


class FakeGoogle:
    """The token endpoint (verifying the assertion) and the Sheets API."""

    def __init__(self, key_file: Path, *, tabs=("days", "my report"), title="Argus ledger",
                 rows=1000, columns=26):
        self.public = load_pem_private_key(json.loads(key_file.read_text())["private_key"])
        self.tabs = list(tabs)
        self.title = title
        self.grid = {t: [rows, columns] for t in tabs}
        self.requests: list[urllib.request.Request] = []
        self.claims: dict | None = None
        self.writes: list[dict] = []
        self.written: dict[str, list[list[str]]] = {}
        self.cleared: list[str] = []

    def __call__(self, req: urllib.request.Request) -> dict:
        self.requests.append(req)
        url, method = req.full_url, req.get_method()
        if url == sheets.TOKEN_URL:
            return self._token(req)
        if method == "GET":
            return {
                "spreadsheetUrl": "https://docs.google.com/spreadsheets/d/sheet-1/edit",
                "properties": {"title": self.title},
                "sheets": [
                    {"properties": {
                        "title": t,
                        "sheetId": i,
                        "gridProperties": {
                            "rowCount": self.grid.get(t, [1000, 26])[0],
                            "columnCount": self.grid.get(t, [1000, 26])[1],
                        },
                    }} for i, t in enumerate(self.tabs)
                ],
            }
        if url.endswith(":clear"):
            self.cleared.append(_tab_of(url))
            return {}
        if method == "PUT":
            tab = _tab_of(url)
            # Only the DATA tabs must be cleared first — they hold last night's rows.
            # A report tab is created fresh by the rebuild, so it is already empty.
            if tab in DATA_TABS and tab not in self.cleared:
                raise AssertionError(f"{tab} was written before it was cleared")
            self.written[tab] = json.loads(req.data)["values"]
            return {}
        if url.endswith(":batchUpdate"):
            body = json.loads(req.data)
            self.writes.extend(body["requests"])
            replies: list[dict] = []
            for r in body["requests"]:
                if "addSheet" in r:
                    title = r["addSheet"]["properties"]["title"]
                    self.tabs.append(title)
                    self.grid[title] = [1000, 26]
                    replies.append({"addSheet": {"properties": {
                        "title": title, "sheetId": self.tabs.index(title),
                    }}})
                    continue
                if "updateSheetProperties" in r:
                    props = r["updateSheetProperties"]["properties"]
                    grid = props.get("gridProperties") or {}
                    if "rowCount" in grid:
                        # Google resolves the sheet by ID ONLY; a title is ignored.
                        assert "sheetId" in props, "a resize must name a sheetId"
                        title = self.tabs[props["sheetId"]]
                        self.grid[title] = [grid["rowCount"], grid["columnCount"]]
                if "deleteSheet" in r:
                    sheet_id = r["deleteSheet"]["sheetId"]
                    if 0 <= sheet_id < len(self.tabs):
                        self.tabs[sheet_id] = f"__deleted{sheet_id}__"
                replies.append({})
            return {"replies": replies}
        raise AssertionError(f"unexpected {method} {url}")

    def _token(self, req: urllib.request.Request) -> dict:
        form = dict(urllib.parse.parse_qsl(req.data.decode()))
        assert form["grant_type"] == sheets.JWT_BEARER
        header_b64, claims_b64, sig_b64 = form["assertion"].split(".")
        signing_input = f"{header_b64}.{claims_b64}".encode()
        signature = _unb64(sig_b64)
        if not verify(signing_input, signature, self.public):
            raise AssertionError("Google would reject this assertion: bad signature")
        self.claims = json.loads(_unb64(claims_b64))
        assert json.loads(_unb64(header_b64)) == {"alg": "RS256", "typ": "JWT"}
        return {"access_token": "ya29.token", "expires_in": 3599}


def _unb64(part: str) -> bytes:
    import base64
    return base64.urlsafe_b64decode(part + "=" * (-len(part) % 4))


def _tab_of(url: str) -> str:
    """The tab name out of a `values/'tab'…` URL."""
    tail = url.split("/values/", 1)[1]
    return urllib.parse.unquote(tail.split("!")[0].split(":")[0]).strip("'")


def _csvs(directory: Path, **tabs: list[list[str]]) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    for tab, rows in tabs.items():
        with (directory / f"{tab}.csv").open("w", newline="") as fh:
            csv.writer(fh).writerows(rows)
    return directory


# -- the login ----------------------------------------------------------------


@needs_openssl
def test_check_signs_in_and_reports_the_spreadsheet(key_file):
    google = FakeGoogle(key_file)

    account, sheet = check(key_file, "sheet-1", google)

    assert account.client_email == EMAIL
    assert (sheet.title, sheet.id) == ("Argus ledger", "sheet-1")
    assert google.requests[1].headers["Authorization"] == "Bearer ya29.token"


@needs_openssl
def test_the_assertion_carries_the_claims_google_requires(key_file):
    google = FakeGoogle(key_file)
    before = int(time.time())

    check(key_file, "sheet-1", google)

    claims = google.claims
    assert claims["iss"] == EMAIL
    assert claims["scope"] == SCOPE == "https://www.googleapis.com/auth/spreadsheets"
    assert claims["aud"] == sheets.TOKEN_URL
    assert before <= claims["iat"] <= int(time.time())
    assert claims["exp"] - claims["iat"] == 3600, "Google allows at most an hour"


@needs_openssl
def test_the_assertion_is_three_dot_separated_parts_and_carries_no_key(key_file):
    account = load_key(key_file)
    assertion = build_assertion(account, now=1_700_000_000)

    assert assertion.count(".") == 2
    assert "PRIVATE KEY" not in assertion
    assert str(account) == f"service account {EMAIL}", "never renders the key"


