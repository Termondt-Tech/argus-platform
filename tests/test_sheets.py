@needs_openssl
def test_a_tab_with_no_csv_is_left_alone(key_file, tmp_path):
    """Before the broker step exists there is no broker_txns.csv, and an empty tab
    would read as "the broker reported nothing"."""
    google = FakeGoogle(key_file, tabs=DATA_TABS)

    sheets.push(key_file, "sheet-1", _csvs(tmp_path / "l", days=[["a"], ["1"]]), google)

    urls = " ".join(r.full_url for r in google.requests)
    assert "broker_txns" not in urls and "recon" not in urls
    assert google.cleared == ["days"]


@needs_openssl
def test_a_cell_that_would_become_a_formula_is_refused(key_file, tmp_path):
    google = FakeGoogle(key_file, tabs=DATA_TABS)
