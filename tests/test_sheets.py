def test_the_sheets_module_cannot_reach_a_database_or_the_broker():
    """It runs with no `--config`; that is only safe while it has no path to a
    database or to anything that trades."""
    tree = ast.parse(Path(sheets.__file__).read_text())
    imported = {
        n.module for n in ast.walk(tree) if isinstance(n, ast.ImportFrom) and n.module
    } | {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names}
    assert not any(m == "sqlite3" or m.startswith("tastytrade") for m in imported)
    allowed = {"argus.tools.rs256", "argus.tools.sheets_report", "argus.tools"}
    assert not [m for m in imported if m.startswith("argus") and m not in allowed]
